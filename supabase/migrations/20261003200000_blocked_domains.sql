create or replace function public.get_capture(p_slug text)
returns table (
  slug           text,
  title          text,
  captured_at    timestamptz,
  source         text,
  format_version smallint,
  size_bytes     integer,
  stats          jsonb,
  views_count    bigint,
  domain         text,
  path           text,
  page_title     text,
  page_versions  integer
)
language sql
stable
set search_path = ''
as $$
  select c.slug, c.title, c.captured_at, c.source, c.format_version, c.size_bytes, c.stats,
         c.views_count, s.domain, p.path, p.title, p.captures_count
    from public.captures c
    join public.pages p on p.id = c.page_id
    join public.sites s on s.id = p.site_id
   where c.slug = p_slug
     and c.status = 'visible'
     and not public.is_blocked_domain(s.domain)
$$;

