    from public.sites s
   where s.domain = p_domain
     and s.pages_count > 0
     and not public.is_blocked_domain(s.domain)
$$;

create or replace function public.site_pages(p_domain text)
returns table (
  path            text,
  title           text,
  captures_count  integer,
  last_capture_at timestamptz,
  latest_slug     text
)
language sql
stable
set search_path = ''
as $$
  select p.path, p.title, p.captures_count, p.last_capture_at,
         (select c.slug
            from public.captures c
           where c.page_id = p.id and c.status = 'visible'
           order by c.captured_at desc
           limit 1)
    from public.pages p
    join public.sites s on s.id = p.site_id
   where s.domain = p_domain
     and p.captures_count > 0
     and not public.is_blocked_domain(s.domain)
   order by p.path
$$;

create or replace function public.site_city(
  p_domain text,
  p_as_of  timestamptz default now()
)
returns table (
  path           text,
  title          text,
  slug           text,
  captured_at    timestamptz,
  source         text,
  format_version smallint,
  size_bytes     integer,
  stats          jsonb
)
language sql
stable
set search_path = ''
as $$
  select t.*
    from (
      select distinct on (p.id)
             p.path, c.title, c.slug, c.captured_at, c.source,
             c.format_version, c.size_bytes, c.stats
        from public.sites s
        join public.pages p on p.site_id = s.id
        join public.captures c on c.page_id = p.id
       where s.domain = p_domain
         and not public.is_blocked_domain(s.domain)
         and c.status = 'visible'
         and c.captured_at <= p_as_of
       order by p.id, c.captured_at desc
    ) t
   order by t.path
$$;

