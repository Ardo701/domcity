-- The domain and all those that contain it, from most precise to broadest.
create or replace function public.domain_suffixes(p_domain text)
returns text[]
language sql
immutable
strict
set search_path = ''
as $$
  select coalesce(array_agg(array_to_string(l.labels[i:], '.') order by i), '{}')
    from (select string_to_array(rtrim(lower(p_domain), '.'), '.') as labels) l,
         generate_subscripts(l.labels, 1) as i
$$;

-- Reads the list without showing it: visitors have no privileges on the table.
create or replace function public.is_blocked_domain(p_domain text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.blocked_domains b
     where b.domain = any (public.domain_suffixes(p_domain))
  )
$$;

-- The whole list, for the browser (a few thousand rows) and for the server when sharing.
create or replace function public.blocklist()
returns table (domain text, category text)
language sql
stable
security definer
set search_path = ''
as $$
  select b.domain, b.category
    from public.blocked_domains b
   order by b.domain
$$;

revoke execute on function public.domain_suffixes(text) from public, anon, authenticated;
grant execute on function public.domain_suffixes(text) to service_role;
grant execute on function
  public.is_blocked_domain(text),
  public.blocklist()
  to anon, authenticated, service_role;


